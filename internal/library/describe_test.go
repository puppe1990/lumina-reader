func TestDescribe_RealAcervoKeys(t *testing.T) {
	casos := []struct {
		nome     string
		key      string
		titulo   string
		autor    string
		category string
		format   string
	}{
		{
			nome:     "autor e pasta do livro",
			key:      "Autoajuda e Desenvolvimento Pessoal/Andrea Furesz/The 5x5 Method/The 5x5 Method A Mental Technique to Develop an Abundance Mindset.epub",
			titulo:   "The 5x5 Method A Mental Technique to Develop an Abundance Mindset",
			autor:    "Andrea Furesz",
			category: "Autoajuda e Desenvolvimento Pessoal",
			format:   "epub",
		},
		{
			nome:     "arquivo solto com prefixo numerico",
			key:      "Autoajuda e Desenvolvimento Pessoal/502745899-O-PODER-DA-VISUALIZACAO-CRIATIVA.pdf",
			titulo:   "O PODER DA VISUALIZACAO CRIATIVA",
			autor:    "",
			category: "Autoajuda e Desenvolvimento Pessoal",
			format:   "pdf",
		},
		{
			nome:     "sufixo z-library derrubado",
			key:      "Tecnologia e Sociedade/Out of Control The New Biology of Machines, Social Systems,  the Economic World (Kevin Kelly) (z-library.sk, 1lib.sk, z-lib.sk).pdf",
			titulo:   "Out of Control The New Biology of Machines, Social Systems, the Economic World (Kevin Kelly)",
			autor:    "",
			category: "Tecnologia e Sociedade",
			format:   "pdf",
		},
		{
			nome:     "autor com virgula na pasta",
			key:      "Comunicacao e Influencia/Ivan Misner, Hazel M. Walker/Business Networking and Sex.epub",
			titulo:   "Business Networking and Sex",
			autor:    "Ivan Misner, Hazel M. Walker",
			category: "Comunicacao e Influencia",
			format:   "epub",
		},
		{
			nome:     "prefixo ebook removido",
			key:      "Espiritualidade e Esoterismo/612742109-E-book-Bioenergia-do-Dinheiro.pdf",
			titulo:   "Bioenergia do Dinheiro",
			autor:    "",
			category: "Espiritualidade e Esoterismo",
			format:   "pdf",
		},
		{
			nome:     "underscores viram espaco",
			key:      "Negocios e Carreira/Robert C. Martin/Clean_Code_and_The_Clean_Coder.epub",
			titulo:   "Clean Code and The Clean Coder",
			autor:    "Robert C. Martin",
			category: "Negocios e Carreira",
			format:   "epub",
		},
	}

	for _, caso := range casos {
		t.Run(caso.nome, func(t *testing.T) {
			meta, err := Describe(caso.key)
			if err != nil {
				t.Fatalf("Describe(%q) erro = %v", caso.key, err)
			}
			if meta.Title != caso.titulo {
				t.Errorf("Title = %q, want %q", meta.Title, caso.titulo)
			}
			if meta.Author != caso.autor {
				t.Errorf("Author = %q, want %q", meta.Author, caso.autor)
			}
			if meta.Category != caso.category {
				t.Errorf("Category = %q, want %q", meta.Category, caso.category)
			}
			if meta.Format != caso.format {
				t.Errorf("Format = %q, want %q", meta.Format, caso.format)
			}
		})
	}
}

func TestDescribe_RejectsUnsupported(t *testing.T) {
	for _, key := range []string{
		"Psicologia e Terapia/Adam Feinstein/conversion-report.txt",
		"Autoajuda e Desenvolvimento Pessoal/livro.md",
		"Relatorios e Referencias/playbook.html",
		"capa.jpg",
	} {
		if _, err := Describe(key); err == nil {
			t.Errorf("Describe(%q) = nil error, want unsupported-format error", key)
		}
	}
}

// Faker property test: any title generated by fakedata must survive Describe
// untouched when it sits in a clean Categoria/Autor/Arquivo.ext key.
func TestDescribe_PreservesFakedataTitles(t *testing.T) {
	fakedata.Seed(42)
	for i := 0; i < 50; i++ {
		titulo := fakedata.Title()
		key := "Ciencia e Natureza/" + fakedata.Name() + "/" + titulo + ".epub"
		meta, err := Describe(key)
		if err != nil {
			t.Fatalf("Describe(%q) erro = %v", key, err)
		}
		if meta.Title != titulo {
			t.Errorf("Title = %q, want fakedata title %q", meta.Title, titulo)
		}
	}
}

func TestDescribe_FormatsInAcervo(t *testing.T) {
	formatos := map[string]string{
		"Cat/A/livro.epub": "epub",
		"Cat/A/livro.PDF":  "pdf",
		"Cat/A/livro.mobi": "mobi",
		"Cat/A/livro.azw3": "azw3",
	}
	for key, quer := range formatos {
		meta, err := Describe(key)
		if err != nil {
			t.Fatalf("Describe(%q) erro = %v", key, err)
		}
		if meta.Format != quer {
			t.Errorf("Describe(%q).Format = %q, want %q", key, meta.Format, quer)
		}
	}
}
